class Page(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.text, self.title, self.hrefs, self._title = [], [], [], False

    def handle_starttag(self, tag, attrs):
        self._title = tag == "title"
        if tag == "a":
            self.hrefs.append(dict(attrs).get("href") or "")

    def handle_endtag(self, tag):
        self._title = False

    def handle_data(self, data):
        (self.title if self._title else self.text).append(data)


def page(name):
    parsed = Page()
    parsed.feed((SITE / name).read_text(encoding="utf-8"))
    return parsed


def missing(fid, html):
    """A fact not shown with its item where the site map places it."""
    named = [name for name, placed in PLANNED.items() if fid in placed]
    if named:
        # Not shown yet when none of its pages is built (partial mode only).
        built = [name for name in named if name in PAGES]
        return not built or any(fid in unbound(html[name], FACTS) for name in built)
    return all(fid in unbound(html[name], FACTS) for name in PAGES)


def waiting(fid):
    """The unbuilt pages a failing check may still wait for (none when strict)."""
    named = [name for name, placed in PLANNED.items() if fid in placed]
    if any(name in PAGES for name in named):
        return []
    return named or UNBUILT


class Tree(HTMLParser):
    """The visible text of every element, innermost first when it closes."""

    VOID = {"area", "br", "col", "embed", "hr", "img", "input", "link", "meta", "source", "wbr"}
    HIDDEN = {"head", "title", "script", "style", "template"}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack, self.texts = [], []

    def handle_starttag(self, tag, attrs):
        if tag not in self.VOID:
            self.stack.append((tag, []))

    def handle_endtag(self, tag):
        if any(name == tag for name, _ in self.stack):
            while True:  # closes any unclosed elements inside it, too
                name, parts = self.stack.pop()
                self.texts.append(" ".join(" ".join(parts).split()).lower())
                if name == tag:
                    break

    def handle_data(self, data):
        if not any(name in self.HIDDEN for name, _ in self.stack):
            for _, parts in self.stack:
                parts.append(data)

    def close(self):
        super().close()
        while self.stack:  # unclosed elements still count
            self.handle_endtag(self.stack[-1][0])


def shows(text, numbers, words):
    """The text shows every whole number and every word ("8" is not "3.80")."""
    found = set(re.findall(r"\d+(?:[.:]\d+)?", text))
    return all(n in found for n in numbers) and all(
        re.search(r"\b" + re.escape(w) + r"\b", text) for w in words
    )


def unbound(html, facts):
    """Fact ids not shown with their item: the smallest element showing a fact
    must not also show another fact that has item words."""
    tree = Tree()
    tree.feed(html)
    tree.close()
    missing = []
    for fid, (numbers, words) in facts.items():
        found = [text for text in tree.texts if shows(text, numbers, words)]
        node = min(found, key=len) if found else None
        if node is None or (
            words
            and any(
                other != fid and facts[other][1] and shows(node, *facts[other]) for other in facts
            )
        ):
            missing.append(fid)
    return sorted(missing)


def dials(href, digits):
    """A tel: link dials the stated national number, written nationally or
    internationally ("+" and a 1-3 digit country code in place of the trunk 0).
    """
    if not href.startswith("tel:"):
        return False
    number = href[4:].split(";", 1)[0].strip()
    got = re.sub(r"\D", "", number)
    if got == digits:
        return True
    national = digits[1:] if digits.startswith("0") else None
    return bool(
        national
        and number.startswith("+")
        and got.endswith(national)
        and 1 <= len(got) - len(national) <= 3
    )


